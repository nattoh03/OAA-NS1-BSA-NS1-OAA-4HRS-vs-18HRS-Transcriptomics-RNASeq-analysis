#!/bin/bash
#SBATCH --job-name=fastqc_rnaseq
#SBATCH --output=fastqc_%j.out
#SBATCH --error=fastqc_%j.err
#SBATCH --time=02:00:00
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=8
#SBATCH --mem=16G
#SBATCH --partition=day

# Load required modules (adjust module names if your cluster uses specific versions)
module load FastQC/0.12.1-Java-11

module load MultiQC/1.10.1-foss-2020b-Python-3.8.6


# Set paths
RAW_DIR="./raw_data"
OUT_DIR="./fastqc_results"

# Create output directory if it doesn't exist
mkdir -p "$OUT_DIR"

echo "Starting FastQC on raw reads at $(date)"

# Find all compressed FASTQ files recursively and run FastQC in parallel
find "$RAW_DIR" -type f \( -name "*.fastq.gz" -o -name "*.fq.gz" \) | xargs -n 1 -P ${SLURM_CPUS_PER_TASK:-4} fastqc -o "$OUT_DIR"

echo "FastQC completed at $(date)"

# Run MultiQC to generate an aggregated HTML report
echo "Running MultiQC..."
multiqc "$OUT_DIR" -o "$OUT_DIR"

echo "Pipeline finished successfully at $(date)"




